"""The standard-library PNG codec of the magnified pictures (png.py; lab-notebook Requirement 7.9,
design N32).

Every pixel here is generated by the test from a fixed seed. These are fixtures, not results."""

import random
import struct
import zlib

import pytest

from notebook import png
from notebook.errors import NotebookError


def _chunk(kind: bytes, body: bytes) -> bytes:
    return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", zlib.crc32(kind + body))


def _paeth(a: int, b: int, c: int) -> int:
    p = a + b - c
    pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
    if pa <= pb and pa <= pc:
        return a
    return b if pb <= pc else c


def _filtered(pixels: bytes, width: int, height: int, channels: int, kinds: list[int]) -> bytes:
    """The filtered scanlines of `pixels`, row by row, with the filter type of each row (the PNG rules)."""
    stride = width * channels
    out = bytearray()
    previous = bytes(stride)
    for y in range(height):
        row = pixels[y * stride : (y + 1) * stride]
        filtered = bytearray(stride)
        for i in range(stride):
            a = row[i - channels] if i >= channels else 0
            b = previous[i]
            c = previous[i - channels] if i >= channels else 0
            predictor = {0: 0, 1: a, 2: b, 3: (a + b) // 2, 4: _paeth(a, b, c)}[kinds[y]]
            filtered[i] = (row[i] - predictor) & 0xFF
        out += bytes([kinds[y]]) + filtered
        previous = row
    return bytes(out)


def _png(width: int, height: int, colour: int, raw: bytes, *, depth: int = 8, interlace: int = 0) -> bytes:
    header = struct.pack(">IIBBBBB", width, height, depth, colour, 0, 0, interlace)
    chunks = _chunk(b"IHDR", header) + _chunk(b"IDAT", zlib.compress(raw)) + _chunk(b"IEND", b"")
    return png.SIGNATURE + chunks


def _fixture_pixels(width: int, height: int, channels: int, seed: int) -> bytes:
    rng = random.Random(seed)
    return bytes(rng.randrange(256) for _ in range(width * height * channels))


@pytest.mark.parametrize(("colour", "channels"), [(2, 3), (6, 4)])
def test_every_row_filter_decodes_to_the_same_pixels(colour: int, channels: int) -> None:
    width, height = 7, 10
    pixels = _fixture_pixels(width, height, channels, seed=colour)
    kinds = [y % 5 for y in range(height)]
    data = _png(width, height, colour, _filtered(pixels, width, height, channels, kinds))
    image = png.decode(data, "fixture")
    assert (image.width, image.height, image.colour_type) == (width, height, colour)
    assert image.pixels == pixels


@pytest.mark.parametrize(("colour", "channels"), [(2, 3), (6, 4)])
def test_encode_then_decode_is_the_identity(colour: int, channels: int) -> None:
    width, height = 5, 4
    image = png.Image(width, height, colour, _fixture_pixels(width, height, channels, seed=3))
    assert png.decode(png.encode(image), "fixture") == image


def test_encoding_the_same_pixels_twice_gives_the_same_bytes() -> None:
    image = png.Image(3, 2, 2, _fixture_pixels(3, 2, 3, seed=9))
    assert png.encode(image) == png.encode(image)


def test_a_sixteen_bit_picture_is_refused_by_name() -> None:
    data = _png(2, 2, 2, bytes(2 * (1 + 2 * 3 * 2)), depth=16)
    with pytest.raises(NotebookError, match="bit depth 16"):
        png.decode(data, "fixture sheet")


def test_an_interlaced_picture_is_refused() -> None:
    data = _png(2, 2, 2, bytes(2 * (1 + 6)), interlace=1)
    with pytest.raises(NotebookError, match="interlace 1"):
        png.decode(data, "fixture sheet")


def test_a_bad_chunk_crc_is_refused() -> None:
    data = bytearray(_png(2, 2, 2, bytes(2 * (1 + 6))))
    data[-5] ^= 0xFF  # inside the IEND CRC
    with pytest.raises(NotebookError, match="CRC"):
        png.decode(bytes(data), "fixture sheet")


def test_a_file_that_is_not_png_is_refused() -> None:
    with pytest.raises(NotebookError, match="not a PNG"):
        png.decode(b"GIF89a", "fixture sheet")
