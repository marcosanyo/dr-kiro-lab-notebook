"""The crop and the magnification of a sheet (magnify.py; lab-notebook Requirement 7.9, design N32).
The sheets here are fixtures generated by the test: a grey background with one black square that
moves. They are not recorded pictures and their numbers are not results."""

from notebook import png
from notebook.layouts import Layout
from notebook.magnify import Box, magnify, moving_box

BACKGROUND = (200, 200, 200)
SQUARE = (0, 0, 0)
GAP_COLOUR = (255, 255, 255)
CELL_W, CELL_H, GAP = 20, 12, 2
LAYOUT = Layout("fixture", frames=2, rows=1, columns=2, gap=GAP, interval=200, source="fixture")


def _sheet(squares: list[tuple[int, int]]) -> bytes:
    """A 2 x 1 sheet: frame k holds a 3 x 3 black square whose top-left corner is `squares[k]` in its cell."""
    width = LAYOUT.columns * CELL_W + (LAYOUT.columns - 1) * GAP
    rows = []
    for y in range(CELL_H):
        line = bytearray()
        for k in range(LAYOUT.frames):
            for x in range(CELL_W):
                sx, sy = squares[k]
                inside = sx <= x < sx + 3 and sy <= y < sy + 3
                line += bytes(SQUARE if inside else BACKGROUND)
            if k < LAYOUT.frames - 1:
                line += bytes(GAP_COLOUR) * GAP
        rows.append(bytes(line))
        assert len(line) == width * 3
    return png.encode(png.Image(width, CELL_H, 2, b"".join(rows)))


def test_the_box_round_the_moving_square_with_a_margin() -> None:
    image = png.decode(_sheet([(2, 3), (10, 3)]), "fixture")
    # Changed pixels: x 2..4 (frame 0's square, gone in frame 1) and x 10..12 (frame 1's square), y 3..5.
    # Margin 4, clipped to the cell of 20 x 12: x 0..16, y 0..9.
    assert moving_box(image, LAYOUT, CELL_W, CELL_H) == Box(0, 0, 17, 10)


def test_the_magnified_sheet_is_the_box_enlarged_by_the_smallest_whole_number_that_covers_the_cell() -> None:
    result = magnify(_sheet([(2, 3), (10, 3)]), LAYOUT, CELL_W, CELL_H, "fixture")
    # The box is 17 x 10; 20 / 17 and 12 / 10 round up to 2, so each cut-out is 34 x 20, with no gap.
    assert result.box == Box(0, 0, 17, 10)
    assert result.magnification == 2
    out = png.decode(result.data, "fixture")
    assert (out.width, out.height) == (2 * 34, 20)


def test_the_enlarged_squares_are_at_their_scaled_places_in_each_frame() -> None:
    out = png.decode(magnify(_sheet([(2, 3), (10, 3)]), LAYOUT, CELL_W, CELL_H, "fixture").data, "fixture")
    stride = out.width * 3

    def pixel(x: int, y: int) -> tuple[int, int, int]:
        at = y * stride + x * 3
        return tuple(out.pixels[at : at + 3])

    # Frame 0: the square at (2, 3) is at (4, 6) after doubling.
    assert pixel(4, 6) == SQUARE and pixel(0, 0) == BACKGROUND
    # Frame 1 starts at x = 34 in the enlarged sheet; its square at (10, 3) is at (34 + 20, 6).
    assert pixel(34 + 20, 6) == SQUARE and pixel(34 + 4, 6) == BACKGROUND


def test_a_sheet_without_motion_gives_the_whole_cell_and_no_magnification() -> None:
    result = magnify(_sheet([(2, 3), (2, 3)]), LAYOUT, CELL_W, CELL_H, "fixture")
    assert result.box == Box(0, 0, CELL_W, CELL_H)
    assert result.magnification == 1
    out = png.decode(result.data, "fixture")
    # No gap in the magnified sheet: two whole cells side by side.
    assert (out.width, out.height) == (2 * CELL_W, CELL_H)
    source = png.decode(_sheet([(2, 3), (2, 3)]), "fixture")
    assert out.pixels[: CELL_W * 3] == source.pixels[: CELL_W * 3]


def test_the_magnified_sheet_is_a_picture_the_bench_accepts() -> None:
    from bench.pictures import check_picture

    result = magnify(_sheet([(2, 3), (10, 3)]), LAYOUT, CELL_W, CELL_H, "fixture")
    check_picture("image/png", result.data)
